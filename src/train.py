            "",
            "Among these methods, Logistic Regression had the highest pooled out-of-fold F1 (0.807) and fold mean F1 (0.806). It flagged 1 of 4,518 ham messages as spam and missed 211 of 653 spam messages across the pooled out-of-fold predictions. Naive Bayes had no false positives in these folds, while missing 315 of 653 spam messages. These are corpus-level cross-validation results, not guarantees for future messages.",
            "",
